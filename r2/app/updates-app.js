/* Раскладка апдейтов по конкурентам — ОДНА на два экрана.
 *
 * Правило продуктовое, а не оформительское: из N изменений один уходит в «цена
 * изменилась», один в «сняли с публикации», остаток — в новых возможных
 * конкурентов. Взято из вебового отчёта (report.js, markUpdates) и повторено
 * здесь, потому что мобильные экраны показывают те же изменения.
 *
 *   AppUpdates.allocate(ALL_COMPETITORS, n, u, desc)
 *     -> { priceIdx, removedIdx, fresh, freshIds }
 *   AppUpdates.flagged(marks, i)   — есть ли у объекта апдейт
 *   AppUpdates.hoist(ids, marks)   — те, у кого есть, наверх списка
 *
 * `desc` — описание объекта агента. Кандидата судит `AppFilters.inPreset`, то есть
 * ровно то правило, которым строится сама подборка.
 * ⚠️ До 2026-09-01 сюда передавали разобранный пресет и сверяли `AppPreset.matches`.
 * Тот знает вид жилья, комнаты и площадь — и разошёлся с выдачей, как только у
 * «До метро» появился порог по умолчанию. Разбор — в `filters.js`, `inPreset`.
 * Нужна новым конкурентам: они обязаны лежать внутри предустановленной выдачи.
 *
 * Почему отдельный файл. До 2026-08-23 правило жило внутри `report-app.js`, и
 * список конкурентов о нём не знал вовсе — то есть на обзоре у объекта стоял флаг,
 * а на экране со списком тот же объект выглядел обычным (замечено Романом). Держать
 * такое правило в одном из двух экранов нельзя: они обязаны сойтись до объекта, а не
 * до «примерно тех же». Отсюда общий модуль, а не копия.
 *
 * Индексы — в исходном массиве, чтобы обе стороны говорили об одном и том же
 * объекте, а не о позиции в своём отфильтрованном списке.
 */
var AppUpdates = (function () {
  'use strict';

  function allocate(list, n, u, desc) {
    var left = u > 0 ? u : 0;
    var shown = (list || []).slice(0, n);
    var priceIdx = -1, removedIdx = -1, i;

    /* Кандидатов выбирают сами данные: цена — первому с непустым priceDelta,
       снятие — первому со признаком removed. Порядок важен, поэтому «снятие»
       ищется уже с оглядкой на выбранного под цену.

       ⚠️ Флаг «Цена изменилась» отдаётся только АКТИВНОМУ объекту (правило Романа
       2026-08-23). У снятого с публикации динамика по цене может быть и показана,
       но новость про него — что его сняли, а не что он подешевел. До этой правки
       флаг доставался первому попавшемуся с дельтой, и на данных прототипа это был
       снятый объект: экран сообщал про цену объявления, которого уже нет. */
    if (left > 0) {
      for (i = 0; i < shown.length; i++) {
        if (shown[i].priceDelta && !shown[i].removed) { priceIdx = i; left--; break; }
      }
    }
    if (left > 0) {
      for (i = 0; i < shown.length; i++) {
        if (i !== priceIdx && shown[i].removed) { removedIdx = i; left--; break; }
      }
    }

    /* Остаток — новые возможные конкуренты: активные объекты за пределами
       отслеживаемых. Так же делит мир экран конкурентов: до n отслеживаются,
       дальше подборка и архив.

       И они обязаны проходить пресет по объекту агента: «Новый конкурент» по
       определению входит в предустановленную выдачу, потому что именно она и
       формирует набор релевантных конкурентов (правило Романа 2026-08-23).
       Предлагать объект, которого агент не найдёт в подборке, — пустое обещание. */
    var freshIds = [];
    for (i = n; i < list.length && freshIds.length < left; i++) {
      if (list[i].removed) continue;
      if (desc != null && !AppFilters.inPreset(list[i], desc)) continue;
      freshIds.push(i);
    }

    return { priceIdx: priceIdx, removedIdx: removedIdx, fresh: left, freshIds: freshIds };
  }

  /* Есть ли у объекта апдейт. «Новый конкурент» сюда НЕ входит: он не отслеживается,
     а лежит в подборке — в списке отслеживаемых его нет вовсе. */
  function flagged(marks, i) {
    return !!marks && (i === marks.priceIdx || i === marks.removedIdx);
  }

  /* Апдейты — наверх списка (просьба Романа 2026-09-04): агент заходит в раздел за
     тем, что изменилось, и искать это глазами по всему списку он не должен.

     Порядок ВНУТРИ групп сохраняется — это стабильная перестановка, а не сортировка
     по признаку: у отслеживаемых свой порядок (как их набирал агент), и ломать его
     ради апдейтов незачем. Тем же двумя проходами это сделано в вебовом отчёте
     (`report.js`, «Апдейты — наверх списка»); здесь правило записано один раз на два
     экрана приложения, чтобы обзор и список не разошлись — та же причина, по которой
     в этом модуле лежит и сама раскладка. */
  function hoist(ids, marks) {
    var up = [], rest = [];
    (ids || []).forEach(function (i) { (flagged(marks, i) ? up : rest).push(i); });
    return up.concat(rest);
  }

  return { allocate: allocate, flagged: flagged, hoist: hoist };
})();
