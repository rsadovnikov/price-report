/* Сброс демо-состояния: ⌘⇧R (Ctrl+Shift+R на Windows).
 *
 * Прототип помнит в sessionStorage то, что в проде хранилось бы на сервере:
 * включён ли мониторинг по объявлению (`monitoring-on`) и комментарии агента
 * (`comments-app`). Из-за этого сценарий первого входа — «Конкуренты» без числа,
 * поиск, онбординг — отыгрывается один раз на вкладку, а на показе его нужно
 * повторять. Отсюда горячая клавиша: чистим хранилище и возвращаемся в начало.
 *
 * Это инструмент показа, а не часть продукта: в ДС ему не место, поэтому файл
 * лежит рядом с экранами прототипа.
 *
 * ⚠️ ⌘⇧R — это ещё и «жёсткая перезагрузка» браузера. Мы её отменяем, но если
 * какая-то сборка сочетание не отдаст, ничего не сломается: хранилище чистится
 * синхронно, ДО того как браузер успеет перезагрузить страницу.
 *
 * Клавиша ловится по `code`, а не по `key`: в русской раскладке `key` придёт
 * как «К», и проверка по букве R молча перестала бы работать.
 */
(function () {
  'use strict';

  addEventListener('keydown', function (e) {
    if (e.code !== 'KeyR' || !e.shiftKey || !(e.metaKey || e.ctrlKey)) return;
    e.preventDefault();
    try { sessionStorage.clear(); } catch (_) {}
    /* replace, а не href: сброс не должен оставлять след в истории — иначе
       «назад» вернёт на экран, которого в новой сессии ещё не было. */
    location.replace('index.html');
  });
})();
