/* Переключение версии отчёта: ⌘⇧S (Ctrl+Shift+S на Windows).
 *
 * У отчёта две версии — с нижней полкой (по умолчанию с 2026-09-14) и обычная, и на
 * показе их приходится сравнивать туда-обратно. Просьба Романа 2026-09-10: переключаться, не
 * правя адрес. Клавиша переворачивает запомненный флаг и перезагружает страницу — сам
 * флаг живёт в `localStorage` и читается guard'ом в шапке `report.html` до первой
 * отрисовки, поэтому полка не мигает при переключении.
 *
 * Это инструмент показа, а не часть продукта: рядом с экранами, не в ДС. Тот же жанр,
 * что `dev-reset.js`, но отдельным файлом — сброс демо-состояния подключён и на
 * мобильных экранах, а двух версий там нет.
 *
 * ⚠️ Параметр `shelf` из адреса при переключении УБИРАЕТСЯ. Адрес главнее памяти
 * (так решено в guard'е), и оставь мы его — страница вернулась бы в ту же версию,
 * а клавиша выглядела бы сломанной.
 *
 * Клавиша ловится по `code`, а не по `key`: в русской раскладке `key` придёт как «ы».
 */
(function () {
  'use strict';

  addEventListener('keydown', function (e) {
    if (e.code !== 'KeyS' || !e.shiftKey || !(e.metaKey || e.ctrlKey)) return;
    e.preventDefault();

    var on = document.documentElement.getAttribute('data-shelf') === '1';
    try { localStorage.setItem(window.SHELF_FLAG_KEY, on ? '0' : '1'); } catch (_) {}

    var u = new URL(location.href);
    u.searchParams.delete('shelf');
    /* replace, а не href: переключение версии — не шаг сценария, и «назад» не должно
       возвращать в предыдущую версию того же экрана. Так же сделан `dev-reset.js`. */
    location.replace(u.pathname + u.search + u.hash);
  });
})();
